defmodule OzMcp.Outbound do
  @moduledoc """
  Requests the server sends to the client.

  A callback (`tool.call/2`, `resource.read/2`, `prompt.get/2`, a task tool)
  can ask the client something while it runs: `ping/2` and the client
  features built on `request/4`, which `OzMcp.Client` wraps (sampling,
  elicitation, roots). The guide about the requests to the client
  describes each method with an example.

  `request/4` sends one JSON-RPC request and blocks the calling process
  until the client answers, the timeout elapses, or the session ends:

      case OzMcp.Outbound.ping(ctx) do
        {:ok, %{}} -> :alive
        {:error, reason} -> {:unreachable, reason}
      end

  ## Results

  `{:ok, result}` when the client answered (a map). A failure gives one
  of these errors: `{:error, {:rpc_error, error}}` (the client answered
  with a JSON-RPC error), `{:error, :timeout}`, `{:error,
  :session_terminated}`, `{:error, :session_not_found}`,
  `{:error, :capability_not_supported}`, `{:error, :unsupported_method}`,
  `{:error, :not_encodable}`, `{:error, :no_task}`, `{:error, :no_stream}`
  and `{:error, :session_not_initialized}`. `request_task/4` adds
  `{:error, :client_tasks_disabled}` (the runtime option `client_tasks`
  is `false`, the default), `{:error, {:client_task_cancelled, task_id}}`
  and `{:error, {:invalid_response, result}}`. The guide about the
  requests to the client gives the meaning of each error and the option
  `:wait_for_stream` of the `:no_stream` case.

  ## Capabilities

  Only a method whose capability the client declared is sent: `ping`
  needs none, `sampling/createMessage` needs `sampling`,
  `elicitation/create` needs `elicitation`, `roots/list` needs `roots`.
  Some params need a member of the capability: a `task` key needs the
  task capability of the method, the modes of `elicitation/create` need
  `elicitation.form` or `elicitation.url` and sampling with `tools`,
  `toolChoice` or `includeContext` needs `sampling.tools` or
  `sampling.context`. The guide about the requests to the client gives
  the table. The three `tasks/*` methods are internal to the flow of a
  client task (see `OzMcp.Client`): a callback does not send them.

  ## Where the request travels

  The callback runs for a `POST` request, as a task, or outside a
  request. A callback of a `POST` request writes the request on the
  response of that `POST`, which becomes an event stream (see
  OzMcp.PostStream). A callback that runs as a task
  (`ctx.task_id` is set) writes the request on the `tasks/result`
  streams of the task and the task is `input_required` while it waits.
  In every other case the request travels on the `GET` stream of the
  session and waits in the event log of the session until a stream
  delivers it. The guide about the requests to the client describes each
  way and the timeout of each method.

  The client answers with a `POST` that carries a JSON-RPC response. The
  router hands the answer to the waiting process with `deliver/2`: an
  answer for a request of a task goes to the process of the task, by the
  owner of the task. Any session of the owner can answer; an answer on a
  session that does not own the task is ignored.

  ## Pending requests

  A pending request of a session lives in the process of the session:
  the session gives each one its id, routes its messages and hands the
  answer to the process that waits. The end of the session process ends
  each wait and a callback that is cancelled, stopped at its deadline
  or killed leaves no pending request: the client receives
  `notifications/cancelled` for it. A late answer for an unknown request
  id is ignored. The request id is generated by the server and is unique
  in the session; a client can answer only the requests of its own
  session.

  ## Telemetry

  Each call of `request/4` gives one `client_request` span of the events
  of `:telemetry`. The guide about the telemetry describes the events.
  """

  alias OzMcp.{Context, PostStream, Session, Sessions, Tasks, Telemetry}
  alias OzMcp.Tasks.RelatedTask
  alias OzMcp.Utils.JsonRpc
  alias OzMcp.Wire

  require Logger

  @answer_tag :oz_mcp_client_answer

  @methods %{
    "ping" => nil,
    "sampling/createMessage" => "sampling",
    "elicitation/create" => "elicitation",
    "roots/list" => "roots",
    "tasks/get" => "tasks",
    "tasks/result" => "tasks",
    "tasks/cancel" => [:tasks, :cancel]
  }

  @type ctx :: Context.ctx() | Context.t()

  @type error ::
          {:rpc_error, map()}
          | :timeout
          | :session_terminated
          | :session_not_found
          | :no_stream
          | :session_not_initialized
          | :capability_not_supported
          | :unsupported_method
          | :not_encodable
          | :no_task
          | :client_tasks_disabled
          | {:client_task_cancelled, String.t()}
          | {:invalid_response, map()}

  @type outcome :: {:ok, map()} | {:error, error()}

  @doc """
  Sends a request to the client and waits for its answer.

  Options:

    * `:timeout` — milliseconds, or `:infinity`. Defaults to the timeout
      runtime option of the method (see the moduledoc).
    * `:wait_for_stream` — `true` sends a request that only the `GET` stream
      can carry even when the client has no stream open (default `false`,
      the call fails with `:no_stream`).
  """
  @spec request(ctx(), String.t(), map() | nil, keyword()) :: outcome()
  def request(ctx, method, params \\ nil, opts \\ [])

  def request(%Context{} = context, method, params, opts),
    do: request(Context.to_ctx(context), method, params, opts)

  def request(%{instance: instance} = ctx, method, params, opts) when is_binary(method) do
    Telemetry.span(
      Telemetry.handle(instance),
      :client_request,
      %{method: bound_method(method)},
      nil,
      fn ->
        result = do_request(ctx, instance, method, params, opts)
        {result, %{result: result_tag(result)}}
      end
    )
  end

  @doc """
  Sends a request as a task of the client and waits for the final result.
  This feature is experimental and the runtime option `client_tasks` turns
  it on (default `false`).

  Same options as `request/4` and:

    * `:ttl` — milliseconds that the client must keep the task. Defaults to
      the timeout of the method when it is an integer; with
      `timeout: :infinity` the request carries no `ttl`.
    * `:poll_interval` — milliseconds between two `tasks/get` calls. The
      `pollInterval` of the client wins. Defaults to the
      `client_task_poll_interval_ms` runtime option.

  The first request carries `params.task`. A `task` value that the params
  already have is kept: the `:ttl` option applies only when the params have
  no `task`. The client answers with a `CreateTaskResult` and the call
  polls `tasks/get` until the task is terminal. A `completed` or `failed`
  task is read with `tasks/result`; an `input_required` task calls
  `tasks/result` at once; a `cancelled` task gives
  `{:error, {:client_task_cancelled, task_id}}`.

  The client must declare the task capability of the method
  (`tasks.requests.sampling.createMessage`,
  `tasks.requests.elicitation.create`), else the call gives
  `{:error, :capability_not_supported}`.
  """
  @spec request_task(ctx(), String.t(), map(), keyword()) :: outcome()
  def request_task(ctx, method, params, opts \\ [])

  def request_task(%Context{} = context, method, params, opts),
    do: request_task(Context.to_ctx(context), method, params, opts)

  def request_task(%{instance: instance} = ctx, method, params, opts) do
    Telemetry.span(
      Telemetry.handle(instance),
      :client_task,
      %{method: bound_method(method)},
      nil,
      fn ->
        result =
          if client_tasks?(ctx) do
            OzMcp.Outbound.ClientTask.run(ctx, method, params, opts)
          else
            {:error, :client_tasks_disabled}
          end

        {result, %{result: task_tag(result)}}
      end
    )
  end

  # `true` when the instance lets a callback run a request as a client task
  # (the runtime option `client_tasks`).
  #
  @doc false
  @spec client_tasks?(ctx() | Context.t()) :: boolean()
  def client_tasks?(%{instance: instance}), do: OzMcp.Instance.opts(instance).client_tasks

  defp do_request(ctx, instance, method, params, opts) do
    session_id = Map.get(ctx, :session_id)
    route = route_of(ctx)

    with {:ok, capability} <- fetch_capability(method),
         {:ok, capabilities} <- fetch_capabilities(ctx),
         :ok <- check_capability(capabilities, capability),
         :ok <- check_params(capabilities, method, params),
         :ok <- check_task(capabilities, method, params),
         :ok <- check_encodable(method, params_for(route, params, method)),
         :ok <- check_route(instance, session_id, route, opts) do
      timeout = timeout(instance, method, opts)

      send_and_wait(
        instance,
        route,
        session_id,
        method,
        params_for(route, params, method),
        timeout
      )
    end
  end

  defp bound_method(method) when is_map_key(@methods, method), do: method
  defp bound_method(_method), do: :unknown

  defp result_tag({:ok, _}), do: :ok
  defp result_tag({:error, {:rpc_error, _}}), do: :rpc_error
  defp result_tag({:error, reason}) when is_atom(reason), do: reason
  defp result_tag(_), do: :error

  defp task_tag({:error, {:client_task_cancelled, _}}), do: :client_task_cancelled
  defp task_tag({:error, {:invalid_response, _}}), do: :invalid_response
  defp task_tag(result), do: result_tag(result)

  @doc """
  Sends `ping` to the client. The client answers with an empty result.
  """
  @spec ping(ctx(), keyword()) :: outcome()
  def ping(ctx, opts \\ []), do: request(ctx, "ping", nil, opts)

  @doc """
  Hands the answer of the client to the process that waits for it.

  `answer` is `{:ok, result}` or `{:error, error}` (the error object of the
  response). Always returns `:ok`: an answer for a request that is not
  pending (late, repeated, unknown, or of another session) is ignored.

  This is the path to one session: the id must name a request that the
  session holds. The router uses `deliver/2`, which sends the answer of a
  request of a task to the task of its owner. An id of a request of a task
  that reaches this function names no request of the session, so the
  answer is ignored.
  """
  @spec deliver(
          OzMcp.Instance.t(),
          String.t(),
          String.t() | integer(),
          {:ok, map()} | {:error, map()}
        ) ::
          :ok
  def deliver(instance, session_id, request_id, answer),
    do: Sessions.deliver(instance, session_id, request_id, outcome(answer))

  # The transport hands the answer of the client here, with the context of
  # the request that carried it. An id of a request of a task
  # ("t.<task_id>.<n>") goes to the process of the task: any session of
  # the owner of the task can answer. Every other id goes to the session
  # that received the answer (deliver/4).
  #
  @doc false
  @spec deliver(Context.t(), {:ok, map()} | {:error, map()}) :: :ok
  def deliver(%Context{rpc_id: "t." <> _rest = out_id} = context, answer) do
    owner_key = Tasks.owner_key(context)
    Tasks.deliver(context.instance, owner_key, context.principal, out_id, outcome(answer))
  end

  def deliver(%Context{} = context, answer),
    do: deliver(context.instance, context.session_id, context.rpc_id, answer)

  defp outcome({:ok, result}), do: {:ok, result}
  defp outcome({:error, error}), do: {:error, {:rpc_error, error}}

  # The tag of the message that the process of a request gets when the
  # client answers. One function, so the sender of the answer and the
  # process that waits use the same atom.
  #
  @doc false
  def answer_tag, do: @answer_tag

  # `true` when the client capabilities accept the method and its params:
  # the method is one a server can send, the client declared the
  # capability it needs and the params agree with the members of the
  # capability. `request/4` and the process of a task use the same rule
  # (a request of a task goes only to a stream whose client accepts it).
  #
  @doc false
  @spec accepts?(map(), String.t(), map() | nil) :: boolean()
  def accepts?(capabilities, method, params)
      when is_map(capabilities) and is_binary(method) do
    case fetch_capability(method) do
      {:ok, capability} ->
        check_capability(capabilities, capability) == :ok and
          check_params(capabilities, method, params) == :ok and
          check_task(capabilities, method, params) == :ok

      {:error, _reason} ->
        false
    end
  end

  # ---- Validation ----

  defp fetch_capability(method) do
    case Map.fetch(@methods, method) do
      {:ok, capability} -> {:ok, capability}
      :error -> {:error, :unsupported_method}
    end
  end

  # The capabilities travel in the ctx (no call); a ctx built by hand is
  # answered from the session.
  #
  defp fetch_capabilities(%{session_id: nil}), do: {:error, :session_not_found}

  defp fetch_capabilities(ctx) do
    case Context.fetch_client_capabilities(ctx) do
      {:ok, capabilities} -> {:ok, capabilities}
      :error -> {:error, :session_not_found}
    end
  end

  defp check_capability(_capabilities, nil), do: :ok

  defp check_capability(capabilities, capability) do
    if Context.capability?(capabilities, capability),
      do: :ok,
      else: {:error, :capability_not_supported}
  end

  # Members of the capability the params depend on:
  #
  #   * `elicitation/create` in `form` mode needs the `form` mode (an empty
  #     `elicitation` object means form only), in `url` mode the `url` mode;
  #   * `sampling/createMessage` with `tools` or `toolChoice` needs
  #     `sampling.tools`; `includeContext` other than `none` needs
  #     `sampling.context`.
  #
  defp check_params(capabilities, "elicitation/create", params) do
    mode = if param(params, "mode", :mode) == "url", do: "url", else: "form"
    elicitation = elicitation_modes(capabilities)

    supported? =
      case mode do
        "url" ->
          is_map(elicitation) and Map.has_key?(elicitation, "url")

        "form" ->
          elicitation == %{} or (is_map(elicitation) and Map.has_key?(elicitation, "form"))
      end

    if supported?, do: :ok, else: {:error, :capability_not_supported}
  end

  defp check_params(capabilities, "sampling/createMessage", params) do
    cond do
      (param(params, "tools", :tools) not in [nil, []] or
         param(params, "toolChoice", :toolChoice) != nil) and
          not Context.capability?(capabilities, [:sampling, :tools]) ->
        {:error, :capability_not_supported}

      param(params, "includeContext", :includeContext) in ["thisServer", "allServers"] and
          not Context.capability?(capabilities, [:sampling, :context]) ->
        {:error, :capability_not_supported}

      true ->
        :ok
    end
  end

  defp check_params(_capabilities, _method, _params), do: :ok

  # A mode with a null value is the same as a missing mode: a client that
  # declares `{"elicitation": {"form": null}}` supports the form mode.
  #
  defp elicitation_modes(capabilities) do
    case Map.get(capabilities, "elicitation") do
      %{} = modes -> Map.reject(modes, fn {_mode, value} -> is_nil(value) end)
      other -> other
    end
  end

  # A request with a `task` key needs the task capability of its method: the
  # client then answers with a `CreateTaskResult` instead of a result.
  #
  defp check_task(capabilities, method, params) do
    if is_nil(param(params, "task", :task)) or Context.task_capability?(capabilities, method),
      do: :ok,
      else: {:error, :capability_not_supported}
  end

  # The request is encoded by the sender, never by the process that writes
  # the stream: a term that JSON cannot encode is refused here.
  #
  defp check_encodable(method, params) do
    case Wire.encode_message(JsonRpc.request(0, method, params)) do
      {:ok, _data} -> :ok
      {:error, :not_encodable} -> {:error, :not_encodable}
    end
  end

  defp param(params, key, atom_key) when is_map(params),
    do: Map.get(params, key) || Map.get(params, atom_key)

  defp param(_params, _key, _atom_key), do: nil

  # A request of a task is held for the `tasks/result` stream of the task and
  # needs no stream now. A request that travels on the stream of its POST
  # request always has a way to the client. Any other needs the GET stream of
  # the session.
  #
  defp check_route(_instance, _session_id, {:task, _task_id}, _opts), do: :ok

  defp check_route(instance, session_id, {:request, request_id}, opts) do
    case PostStream.owner(instance, session_id, request_id) do
      {:ok, _owner} ->
        :ok

      :none ->
        case Sessions.delivery(instance, session_id) do
          {:ok, %{initialized: false}} -> {:error, :session_not_initialized}
          {:ok, %{stream?: false}} -> check_wait_for_stream(opts)
          {:ok, _delivery} -> :ok
          _ -> {:error, :session_not_found}
        end
    end
  end

  defp check_wait_for_stream(opts) do
    if Keyword.get(opts, :wait_for_stream, false), do: :ok, else: {:error, :no_stream}
  end

  @doc false
  @spec timeout(OzMcp.Instance.t(), String.t(), keyword()) :: pos_integer() | :infinity
  def timeout(instance, method, opts) do
    case Keyword.get(opts, :timeout) do
      nil -> default_timeout(OzMcp.Instance.opts(instance), method)
      :infinity -> :infinity
      ms when is_integer(ms) and ms > 0 -> ms
      other -> raise ArgumentError, "invalid timeout: #{inspect(other)}"
    end
  end

  # An answer that needs a person gets more time than a machine answer.
  #
  defp default_timeout(opts, "elicitation/create"), do: opts.elicitation_timeout_ms
  defp default_timeout(opts, "sampling/createMessage"), do: opts.sampling_timeout_ms
  defp default_timeout(opts, _method), do: opts.client_request_timeout_ms

  # ---- Sending and waiting ----

  # A request of a task: the process of the task holds it (it made the id
  # and monitors the waiter). The wait ends with the answer of the client
  # or at the timeout: the task tells the client to forget the request
  # and a late answer is dropped. The end of the process of the task ends
  # the wait too (`{:error, :no_task}`), after a last look for an answer
  # that came before it.
  #
  defp send_and_wait(instance, {:task, task_id}, _session_id, method, params, timeout) do
    case Tasks.request(instance, task_id, method, params) do
      {:ok, out_id, task_pid} ->
        ref = Process.monitor(task_pid)

        receive do
          {@answer_tag, ^out_id, outcome} ->
            Process.demonitor(ref, [:flush])
            outcome

          {:DOWN, ^ref, :process, _pid, _reason} ->
            receive do
              {@answer_tag, ^out_id, outcome} -> outcome
            after
              0 -> {:error, :no_task}
            end
        after
          timeout ->
            Process.demonitor(ref, [:flush])
            Logger.warning("the client did not answer #{inspect(method)} within #{timeout} ms")
            Tasks.cancel_request(instance, task_id, out_id)
            flush_answer(out_id)
            {:error, :timeout}
        end

      {:error, reason} ->
        {:error, reason}
    end
  end

  # Any other request: the session stores it and routes its first message
  # (see `OzMcp.Sessions.request_client/4`). The reply of the session gives
  # the id of the request and the pid of the session process. The wait ends
  # with the answer of the client, with an error of the session, or at the
  # timeout: the client is told to forget the request and a late answer is
  # dropped.
  #
  defp send_and_wait(instance, route, session_id, method, params, timeout) do
    case Sessions.request_client(instance, session_id, route, {method, params}) do
      {:ok, out_id, session_pid} ->
        wait_for_answer(instance, session_id, session_pid, out_id, method, timeout)

      {:error, reason} ->
        {:error, reason}
    end
  end

  # The session ends the wait at its normal end: it sends
  # `{:error, :session_terminated}` before it stops. A session that stops
  # with no normal end (a kill) ends the wait with its DOWN. An answer that
  # came before the end of the session wins.
  #
  defp wait_for_answer(instance, session_id, session_pid, out_id, method, timeout) do
    ref = Process.monitor(session_pid)

    receive do
      {@answer_tag, ^out_id, outcome} ->
        Process.demonitor(ref, [:flush])
        outcome

      {:DOWN, ^ref, :process, _pid, _reason} ->
        receive do
          {@answer_tag, ^out_id, outcome} -> outcome
        after
          0 -> {:error, :session_terminated}
        end
    after
      timeout ->
        Process.demonitor(ref, [:flush])
        Logger.warning("the client did not answer #{inspect(method)} within #{timeout} ms")
        _ = Session.cancel_outbound(instance, session_id, out_id)
        flush_answer(out_id)
        {:error, :timeout}
    end
  end

  # ---- Routes ----

  # Where the messages of a request go: the POST request it belongs to, or
  # the task that sends it.
  #
  defp route_of(ctx) do
    case Map.get(ctx, :task_id) do
      task_id when is_binary(task_id) -> {:task, task_id}
      _ -> {:request, Map.get(ctx, :request_id)}
    end
  end

  # The requests of a client task that carry the task id in their params do
  # not get the related-task meta: the id is already there and the
  # specification says not to include it.
  #
  @no_related_task ~w(tasks/get tasks/result tasks/cancel)

  # The request of a task says which task it belongs to.
  #
  defp params_for({:request, _request_id}, params, _method), do: params

  defp params_for({:task, _task_id}, params, method) when method in @no_related_task, do: params

  defp params_for({:task, task_id}, params, _method), do: RelatedTask.put(params, task_id)

  # An answer can arrive while the wait ends: do not leave it in the mailbox.
  #
  defp flush_answer(out_id) do
    receive do
      {@answer_tag, ^out_id, _outcome} -> flush_answer(out_id)
    after
      0 -> :ok
    end
  end
end
